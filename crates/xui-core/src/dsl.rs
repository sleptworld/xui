//! The runtime contract behind the `xui!` and `view!` macros.
//!
//! `view!` is the same DSL spelled like SwiftUI and lowers to the same calls:
//! `tag(name: v)` / `tag().name(v)` is the attribute `name={v}`, `tag(expr)`
//! is [`Content`], and `tag { .. }` is [`Children`].
//!
//! `xui!` is a *purely syntactic* transform. It knows no tag names and no
//! attribute names. Everything a tag accepts is decided here, by the type
//! system:
//!
//! - **Constructor** — `<tag>` requires a function `tag()` in scope returning a
//!   [`Draft`]. Host widgets export theirs from the prelude; components get one
//!   generated by `#[component]`. A misspelled tag is a plain `cannot find
//!   function` error.
//! - **Attributes** — `attr={expr}` asks the draft's property table
//!   ([`NodeDef::Properties`]) for the property `attr` and sets it: a widget's
//!   own props, then those of every capability it selects (an own prop wins
//!   over a capability's of the same name). A closure given to an `on_*`
//!   attribute is a handler; `attr={x.share()}` forwards a component prop
//!   without copying it; `key` is the draft's key. A misspelled attribute is
//!   rustc's own `no method named ... similar name ...`, pointed at the
//!   attribute; one the node lacks is the same error.
//! - **Children** — the macro passes one of [`NoChildren`], [`Children`], or
//!   [`Content`] to [`IntoElement`], which a draft implements through its
//!   node's [`NodeElement`] impls. `<canvas>{x}</canvas>` fails to compile
//!   because `Canvas` only implements `NodeElement<_, NoChildren>`, and a
//!   component draft missing a required prop implements none.
//!
//! Adding a capability property, a widget, or a component therefore never
//! requires a change to `xui-macros`.

