/// What a static element expands to: the call site's one allocation, built on
/// first use in this thread. See `docs/template-slots.md` §5.
#[doc(hidden)]
pub fn hoisted(site: &'static std::thread::LocalKey<std::rc::Rc<Hoisted>>) -> ElementDesc {
    site.with(|hoisted| ElementDesc::Hoisted(hoisted.clone()))
}

