#[cfg(test)]
mod schema_tests {
    //! `xui_schema` describes this module and `crate::widgets` to the macros;
    //! these hold the description to the code.

    use crate::widgets::{Widgets, center, column, container, grid, row, text, z_stack};

    #[test]
    fn the_schema_lists_every_style_attribute_but_scrollbar() {
        let mut table: Vec<_> = super::STYLE_PROP_NAMES
            .iter()
            .copied()
            .filter(|name| *name != "scrollbar")
            .collect();
        let mut schema = xui_schema::STYLE_PROPS.to_vec();
        table.sort_unstable();
        schema.sort_unstable();
        assert_eq!(schema, table);
    }

    #[test]
    fn each_host_tag_builds_the_widget_the_schema_names() {
        for tag in xui_schema::HOST_TAGS {
            let widget: Widgets = match tag.name {
                "container" => container().into(),
                "row" => row().into(),
                "column" => column().into(),
                "center" => center().into(),
                "z_stack" => z_stack().into(),
                "grid" => grid().into(),
                "text" => text().into(),
                other => panic!("no constructor checked for `{other}`"),
            };
            let debug = format!("{widget:?}");
            assert!(
                debug.contains(tag.widget),
                "`{}` builds {debug}, not {}",
                tag.name,
                tag.widget
            );
        }
    }
}
