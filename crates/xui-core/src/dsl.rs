//! The runtime contract behind the `xui!` and `view!` macros.
//!
//! `view!` is the same DSL spelled like SwiftUI and lowers to the same calls:
//! `tag(name: v)` / `tag().name(v)` is `.name(v)`, `tag(expr)` is
//! [`Content`], and `tag { .. }` is [`Children`].
//!
//! `xui!` is a *purely syntactic* transform: `<tag attr={expr}>children</tag>`
//! becomes `tag().attr(expr).into_element(children)`. It knows no tag names and
//! no attribute names. Everything a tag accepts is decided here, by the type
//! system:
//!
//! - **Constructor** — `<tag>` requires a function `tag()` in scope returning a
//!   builder. Host widgets export theirs from [`crate::widgets`] and are
//!   lowercase (`row`, `text`); components get one generated by `#[component]`
//!   and are PascalCase (`fn date_picker` is written `DatePicker`), so the two
//!   never share a name. A misspelled tag is a plain `cannot find function`
//!   error.
//! - **Attributes** — `attr={expr}` is `.attr(expr)`. Style properties come from
//!   the blanket [`StyleProps`] trait, widget-specific ones from inherent
//!   methods (which take precedence over the trait, so a widget can override a
//!   generic property). A misspelled attribute is rustc's own
//!   `no method named ... did you mean ...?`, pointed at the attribute.
//! - **Children** — the macro passes one of [`NoChildren`], [`Children`], or
//!   [`Content`] to [`IntoElement`], and the widget decides which of those it
//!   accepts. `<canvas>{x}</canvas>` fails to compile because `CanvasWidget`
//!   only implements `IntoElement<NoChildren>`.
//!
//! Adding a style property, a widget, or a component therefore never requires a
//! change to `xui-macros`.

