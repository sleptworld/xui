// ---------------------------------------------------------------------------
// Children
// ---------------------------------------------------------------------------

/// `<tag />` — the tag was written without a body.
pub struct NoChildren;

/// `<tag><a /><b /></tag>` — an element list collected by the macro.
pub struct Children(pub Vec<ElementDesc>);

/// `<tag>{expr}</tag>` — a single braced expression, meaning whatever the
/// receiving widget says it means. Containers read it as children (via
/// [`IntoChildren`]); `text` reads it as its text content.
pub struct Content<T>(pub T);

/// Turns a widget or component builder into an [`ElementDesc`], given whatever
/// the macro found between the tags.
///
/// Implement it once per accepted child shape. Not implementing a shape is how
/// a widget rejects it at compile time.
#[diagnostic::on_unimplemented(
    message = "`<{Self}>` does not accept this kind of body",
    label = "not a valid body for this element",
    note = "`NoChildren` = `<tag />` or `tag()`, \
            `Children` = `<tag><a /><b /></tag>` or `tag {{ a() b() }}`, \
            `Content<T>` = `<tag>{{expr}}</tag>` or `tag(expr)`",
    note = "a leaf element such as `canvas` or `icon` accepts no body at all"
)]
pub trait IntoElement<C> {
    fn into_element(self, children: C) -> ElementDesc;
}

/// The three body shapes `xui!` can produce, and the entry point it actually
/// emits.
///
/// Dispatching *from the body* rather than from the widget is what makes the
/// diagnostic above fire. With `build(widget, body)` as a free function, a
/// widget that has exactly one `IntoElement` impl lets inference unify the body
/// type with that impl and the error degrades to `expected NoChildren, found
/// Content<_>`. Here `Self` is pinned by the receiver, so `W: IntoElement<Self>`
/// is a genuine unsatisfied bound.
pub trait ElementBody: Sized {
    fn build<W: IntoElement<Self>>(self, widget: W) -> ElementDesc {
        widget.into_element(self)
    }
}

impl ElementBody for NoChildren {}
impl ElementBody for Children {}
impl<T> ElementBody for Content<T> {}

impl Children {
    pub fn collect(self) -> Vec<ElementDesc> {
        self.0
    }
}

impl<T: IntoChildren> Content<T> {
    pub fn collect(self) -> Vec<ElementDesc> {
        let mut children = Vec::new();
        self.0.append_children(&mut children);
        children
    }
}

// ---------------------------------------------------------------------------
// Host widget wiring
// ---------------------------------------------------------------------------

/// Declares which child shapes a host widget's draft accepts.
macro_rules! impl_host_element {
    (parent $widget:ty) => {
        impl IntoElement<NoChildren> for Draft<$widget> {
            fn into_element(self, _: NoChildren) -> ElementDesc {
                self.into_element_desc(Vec::new())
            }
        }

        impl IntoElement<Children> for Draft<$widget> {
            fn into_element(self, children: Children) -> ElementDesc {
                self.into_element_desc(children.collect())
            }
        }

        impl<T: IntoChildren> IntoElement<Content<T>> for Draft<$widget> {
            fn into_element(self, content: Content<T>) -> ElementDesc {
                self.into_element_desc(content.collect())
            }
        }
    };
    (leaf $widget:ty) => {
        impl IntoElement<NoChildren> for Draft<$widget> {
            fn into_element(self, _: NoChildren) -> ElementDesc {
                self.into_element_desc(Vec::new())
            }
        }
    };
}

impl_host_element!(parent Container);
impl_host_element!(parent Grid);
impl_host_element!(parent ZStack);
impl_host_element!(parent Image);
impl_host_element!(leaf Canvas);
impl_host_element!(leaf Icon);
impl_host_element!(leaf TextInput);

impl IntoElement<NoChildren> for Draft<Text> {
    fn into_element(self, _: NoChildren) -> ElementDesc {
        self.into_element_desc(Vec::new())
    }
}

/// `<text>{expr}</text>` sets the text content rather than adding children.
impl<T: Into<TextContent>> IntoElement<Content<T>> for Draft<Text> {
    fn into_element(self, content: Content<T>) -> ElementDesc {
        self.with::<text::content>(content.0).into_element_desc(Vec::new())
    }
}
