pub use crate::event_system::callbacks::{HandlerEntry, handlers};

/// The static part of a templated host, built once per call site. The type
/// argument names the widget `xui_schema` says the tag builds, so a lowercase
/// tag that resolves to something else is a type error here rather than a
/// widget the slots would misread.
#[doc(hidden)]
pub fn host<W: Into<crate::widgets::Widgets>>(widget: W) -> crate::widgets::WidgetProto {
    crate::widgets::WidgetProto::new(widget)
}

/// The style a templated host's changing style attributes are chained onto.
#[doc(hidden)]
pub fn empty_style() -> Style {
    Style::new()
}

/// `text(..)`'s content as a slot value.
#[doc(hidden)]
pub fn text_content(content: impl Into<TextContent>) -> TextContent {
    content.into()
}

/// A `key` attribute as a slot value.
#[doc(hidden)]
pub fn key(key: impl Into<crate::fiber::Key>) -> crate::fiber::Key {
    key.into()
}

/// A body handed to a templated host: its children, whichever form they were
/// written in.
#[doc(hidden)]
pub trait TemplateBody {
    fn into_children(self) -> Vec<ElementDesc>;
}

impl TemplateBody for NoChildren {
    fn into_children(self) -> Vec<ElementDesc> {
        Vec::new()
    }
}

impl TemplateBody for Children {
    fn into_children(self) -> Vec<ElementDesc> {
        self.collect()
    }
}

impl<T: IntoChildren> TemplateBody for Content<T> {
    fn into_children(self) -> Vec<ElementDesc> {
        self.collect()
    }
}

/// What a templated host expands to on every render: the call site's base and
/// this render's slot values. See `docs/template-slots.md` §12.
#[doc(hidden)]
pub fn templated<const N: usize>(
    site: &'static std::thread::LocalKey<std::rc::Rc<TemplateBase>>,
    key: Option<crate::fiber::Key>,
    style: Option<Style>,
    content: Option<TextContent>,
    handlers: [HandlerEntry; N],
    body: impl TemplateBody,
) -> ElementDesc {
    let installed = (N > 0).then(|| {
        let mut installed = Box::<crate::widgets::EventHandlers>::default();
        for handler in handlers {
            handler.install(&mut installed);
        }
        installed
    });
    ElementDesc::Templated(crate::element::TemplatedDesc {
        base: site.with(std::rc::Rc::clone),
        key,
        slots: crate::element::TemplateSlots {
            style: style.map(Box::new),
            content,
        },
        handlers: installed,
        children: body.into_children(),
    })
}

impl Children {
    pub fn collect(self) -> Vec<ElementDesc> {
        self.0
    }
}

impl<T: IntoChildren> Content<T> {
    pub fn collect(self) -> Vec<ElementDesc> {
        let mut children = Vec::new();
        self.0.append_children(&mut children);
        children
    }
}

