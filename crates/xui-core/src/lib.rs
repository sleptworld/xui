/// Includes the asset bootstrap module generated for this crate.
///
/// Invoke this once at the application crate root. It defines `xui_assets`, containing
/// generated resource constants and a `manager()` constructor.
///
/// The module comes from the crate's build script calling `xui_build::assets()`,
/// or, for a crate without one, from building through `cargo xui`.
#[macro_export]
macro_rules! include_assets {
    () => {
        include!(env!(
            "XUI_ASSETS_BOOTSTRAP",
            "XUI assets are generated by a build script: add `xui-build` to \
             [build-dependencies] and call `xui_build::assets()` from build.rs \
             (`cargo xui init` sets this up), or build through `cargo xui`"
        ));
    };
}
