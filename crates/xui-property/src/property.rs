//! One typed protocol for widget-owned props, capability declarations and slots.
use std::marker::PhantomData;
use crate::core::Dirty;

pub trait Scope { type Storage; }

pub trait Property {
    type Scope: Scope;
    type Value;

    fn get(storage: &<Self::Scope as Scope>::Storage) -> &Self::Value;
    fn replace(storage: &mut <Self::Scope as Scope>::Storage, value: Self::Value);
}

pub trait Access<S: Scope> {
    fn access(&self) -> &S::Storage;
    fn access_mut(&mut self) -> &mut S::Storage;
}

/// Opt-in slot policy. A property can exist without being animatable or
/// comparable (event handlers can use identity comparison instead).
pub trait SlotProperty: Property {
    const HINT: Dirty;
    fn same(a: &Self::Value, b: &Self::Value) -> bool;
}

/// ZST descriptor: no Box<dyn Trait>, no per-slot Rc allocation.
pub struct Slot<P: Property> {
    pub label: &'static str,
    _property: PhantomData<fn() -> P>,
}

impl<P: Property> Slot<P> {
    pub const fn new(label: &'static str) -> Self {
        Self { label, _property: PhantomData }
    }
}

impl<P: SlotProperty> Slot<P> {
    /// Write only if changed; returned flags are candidates for the resolver.
    /// Actual dirty output depends on differences in computed results.
    pub fn apply<T: Access<P::Scope>>(&self, target: &mut T, value: P::Value) -> Dirty {
        if P::same(P::get(target.access()), &value) {
            return Dirty::NONE;
        }
        P::replace(target.access_mut(), value);
        P::HINT
    }
}

/// Type-level name/attribute mapping generated by #[widget]/#[component]
/// and by capability declarations. These are marker keys, not string lookups.
pub trait ResolveAttr<Key> {
    type Property: Property;
}

/// The common, not-yet-implemented expansion layer can resolve the property
/// type through the target's type, even when xui! cannot inspect Rust types.
pub fn mapped_property<Key, Target>() -> PhantomData<<Target as ResolveAttr<Key>>::Property>
where Target: ResolveAttr<Key> {
    PhantomData
}


/// Optional property extension: generated commit metadata explicitly registers
/// only the Properties implementing this trait. Slot<P> never needs runtime
/// trait reflection or specialization.
///
/// `Resource` lives on the mounted instance, not in the shareable declaration.
/// Hooks only run when the Fiber work-in-progress tree actually commits.
pub trait ManagedProperty: Property {
    type Resource: Default;

    fn on_commit(
        old: Option<&Self::Value>,
        new: Option<&Self::Value>,
        resource: &mut Self::Resource,
        ctx: &mut crate::runtime::CommitCtx<'_>,
    );
}

/// The generated per-Widget/CapSet dispatch calls this for selected managed
/// fields. `None` for a *node* means mount/unmount; `Some(None)` for a field
/// whose value is `Option<T>` means the node exists but the binding is cleared.
pub fn commit_managed<P: ManagedProperty>(
    old: Option<&<P::Scope as Scope>::Storage>,
    new: Option<&<P::Scope as Scope>::Storage>,
    resource: &mut P::Resource,
    ctx: &mut crate::runtime::CommitCtx<'_>,
) {
    P::on_commit(old.map(P::get), new.map(P::get), resource, ctx);
}
